// Compound Assignment operators or Shorthand Assignment operators 
// += Addition assignment
// -= Subtraction assignment
// *= Multiplication assignment 
// /= Division assignment
// %= Modulus assignment

let x = 10;
x += 10; // x = x + 10
console.log(x); // Output: 20

x -= 3; // x = x - 3
console.log(x); // Output: 17

x *= 2; // x = x * 2
console.log(x); // Output: 34

x  /= 17; // x = x / 17
console.log(x); // Output: 2

x %= 2; // x = x % 2
