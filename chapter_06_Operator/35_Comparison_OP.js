// Comparison operators are used to compare two values and return a boolean result (true or false).

// >, <, >=, <=, ==, ===, !=, !==

// > Greater than
// < Less than
// >= Greater than or equal to
// <= Less than or equal to
// == Equality (loose equality, checks value only)
// === Strict equality (checks value and type)
// != Inequality (loose inequality, checks value only)
// !== Strict inequality (checks value and type)

console.log(3 > 4); // Output: false
console.log(3 < 4); // Output: true
console.log(3 >= 3); // Output: true
console.log(3 <= 4); // Output: true
console.log(3 == 4); // Output: false
console.log(3 === 3); // Output: true
console.log(3 != 4); // Output: true
console.log(3 !== 4); // Output: true